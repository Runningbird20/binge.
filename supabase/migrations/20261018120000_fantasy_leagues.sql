-- ── 1. ESPN Fantasy leagues per profile (LiveScorePanel → Fantasy tab) ──
-- Which league/team to show for each fantasy game (ffl football, flb
-- baseball, fba basketball, fhl hockey). Not secret: the owner reads/writes
-- it directly.
create table if not exists public.fantasy_leagues (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  profile_id uuid references public.account_profiles(id) on delete cascade,
  game text not null check (game in ('ffl', 'flb', 'fba', 'fhl')),
  league_id text not null check (league_id ~ '^[0-9]{1,12}$'),
  team_id integer,
  updated_at timestamptz not null default now()
);
create unique index if not exists idx_fantasy_leagues_unique
  on public.fantasy_leagues (user_id, coalesce(profile_id, '00000000-0000-0000-0000-000000000000'::uuid), game);
alter table public.fantasy_leagues enable row level security;
drop policy if exists fantasy_leagues_own on public.fantasy_leagues;
create policy fantasy_leagues_own on public.fantasy_leagues
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());

-- ── 2. ESPN cookies for private leagues (service role only) ────────────
-- espn_s2 + SWID act like an ESPN password. They're encrypted by the server
-- (AES-256-GCM, server/routes/sports.js) before they get here, and RLS with
-- no policies means browsers can't read them back even for their own
-- account: only /api/sports/fantasy uses them, server-side.
create table if not exists public.espn_credentials (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  profile_id uuid references public.account_profiles(id) on delete cascade,
  secret text not null,          -- iv.tag.ciphertext (base64url) of {"s2","swid"}
  swid_hint text,                -- last 4 characters, to show which account is saved
  updated_at timestamptz not null default now()
);
create unique index if not exists idx_espn_credentials_unique
  on public.espn_credentials (user_id, coalesce(profile_id, '00000000-0000-0000-0000-000000000000'::uuid));
alter table public.espn_credentials enable row level security;
revoke all on public.espn_credentials from anon, authenticated;
