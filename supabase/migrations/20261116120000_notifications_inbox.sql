-- Notification inbox. Every alert binge. sends (new episodes, reminders,
-- followed-team games, admin announcements, server alerts to admins) is also
-- kept here, so the bell in the header can list the last 30 days after the
-- push itself is gone. The server writes the rows (service role); the app
-- reads its own and may only mark them read. profile_id null means the whole
-- account: every profile sees it. The daily new-episodes cron deletes rows
-- older than 30 days.
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  profile_id uuid references public.account_profiles(id) on delete cascade,
  kind text not null check (kind in ('episode', 'reminder', 'game', 'announcement', 'server')),
  title text not null check (char_length(title) <= 200),
  body text not null default '' check (char_length(body) <= 500),
  url text check (url is null or (url like '/%' and char_length(url) <= 500)),
  created_at timestamptz not null default now(),
  read_at timestamptz
);
create index if not exists idx_notifications_user_created
  on public.notifications (user_id, created_at desc);
create index if not exists idx_notifications_created on public.notifications (created_at);
alter table public.notifications enable row level security;
drop policy if exists notifications_read_own on public.notifications;
create policy notifications_read_own on public.notifications
  for select using (user_id = auth.uid());
drop policy if exists notifications_mark_own on public.notifications;
create policy notifications_mark_own on public.notifications
  for update using (user_id = auth.uid()) with check (user_id = auth.uid());
revoke all on public.notifications from anon, authenticated;
grant select on public.notifications to authenticated;
grant update (read_at) on public.notifications to authenticated;
