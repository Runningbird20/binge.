-- The bell on a series (RemindButton): alerts for its new episodes and new
-- seasons, on or off per profile. A show on the profile's list (not finished)
-- or in its Continue Watching is followed already; a row here overrides that:
-- following = true follows a show that isn't (or no longer is) on the list,
-- following = false mutes one that is. The daily new-episodes job
-- (server/routes/cron.js) reads both. media_id is tv_shows.id (the catalog,
-- in Turso: no foreign key).
create table if not exists public.show_alerts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  profile_id uuid references public.account_profiles(id) on delete cascade,
  media_id bigint not null,
  following boolean not null,
  updated_at timestamptz not null default now()
);
create unique index if not exists show_alerts_one_per_profile
  on public.show_alerts (user_id, coalesce(profile_id, '00000000-0000-0000-0000-000000000000'::uuid), media_id);
alter table public.show_alerts enable row level security;
drop policy if exists show_alerts_read_own on public.show_alerts;
create policy show_alerts_read_own on public.show_alerts for select using (user_id = auth.uid());
drop policy if exists show_alerts_insert_own on public.show_alerts;
create policy show_alerts_insert_own on public.show_alerts for insert with check (user_id = auth.uid());
drop policy if exists show_alerts_update_own on public.show_alerts;
create policy show_alerts_update_own on public.show_alerts for update using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists show_alerts_delete_own on public.show_alerts;
create policy show_alerts_delete_own on public.show_alerts for delete using (user_id = auth.uid());
revoke all on public.show_alerts from anon, authenticated;
grant select, insert, update, delete on public.show_alerts to authenticated;

-- New-season announcements: how many seasons (specials aside) TMDB listed for
-- each followed show at the last daily check. A higher count is a new season
-- announced; a show seen for the first time is only recorded. Server only.
create table if not exists public.show_seasons_seen (
  media_id bigint primary key,
  seasons integer not null,
  checked_at timestamptz not null default now()
);
alter table public.show_seasons_seen enable row level security;
revoke all on public.show_seasons_seen from anon, authenticated;
